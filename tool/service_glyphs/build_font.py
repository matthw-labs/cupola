"""Builds the service glyph font and its Dart constants from `svg/`.

    python3 tool/service_glyphs/build_font.py

Needs `fonttools` and `skia-pathops` (pip). Writes
`assets/fonts/CupolaServices.otf` and `lib/core/service_glyphs.dart`; both are
generated, so edit the SVGs or this script and rebuild rather than touching
either output.

Every source is a 24x24 viewBox filled shape. Its paths are unioned through
Skia's path ops first, which resolves each path's own `fill-rule`; several
marks cut their holes with `evenodd`, and a font only has nonzero winding.
"""

import pathlib
import re
import xml.etree.ElementTree as ET

import pathops
from fontTools.fontBuilder import FontBuilder
from fontTools.pens.t2CharStringPen import T2CharStringPen
from fontTools.pens.transformPen import TransformPen
from fontTools.svgLib.path import parse_path

ROOT = pathlib.Path(__file__).resolve().parents[2]
SRC = ROOT / "tool/service_glyphs/svg"
FONT = ROOT / "assets/fonts/CupolaServices.otf"
DART = ROOT / "lib/core/service_glyphs.dart"

FAMILY = "CupolaServices"
UPM = 1200
BOX = 24.0

# (ServiceKey name, source file, code point). Code points are stable: a glyph
# keeps its slot for as long as the service exists, so a rebuilt font never
# repaints one service's glyph as another's.
GLYPHS = [
    ("seerr", "seerr", 0xE001),
    ("radarr", "radarr", 0xE002),
    ("sonarr", "sonarr", 0xE003),
    ("lidarr", "lidarr", 0xE004),
    ("qbittorrent", "qbittorrent", 0xE005),
    ("transmission", "transmission", 0xE006),
    ("bazarr", "bazarr", 0xE007),
    ("truenas", "truenas", 0xE008),
    ("dockge", "dockge", 0xE009),
    ("prowlarr", "prowlarr", 0xE00A),
    ("readarr", "readarr", 0xE00B),
    ("sabnzbd", "sabnzbd", 0xE00C),
    ("nzbget", "nzbget", 0xE00D),
    ("unraid", "unraid", 0xE00E),
    ("nginxProxyManager", "nginx_proxy_manager", 0xE00F),
    ("jellyfin", "jellyfin", 0xE010),
    ("plex", "plex", 0xE011),
    ("emby", "emby", 0xE012),
]

NS = "{http://www.w3.org/2000/svg}"


def outline(svg_path: pathlib.Path) -> pathops.Path:
    root = ET.parse(svg_path).getroot()
    vb = [float(v) for v in re.split(r"[ ,]+", root.get("viewBox").strip())]
    if vb != [0, 0, BOX, BOX]:
        raise SystemExit(f"{svg_path.name}: viewBox must be 0 0 24 24, got {vb}")
    union = pathops.Path()
    for node in root.iter(f"{NS}path"):
        part = pathops.Path()
        parse_path(node.get("d"), part.getPen())
        part.fillType = (
            pathops.FillType.EVEN_ODD
            if node.get("fill-rule") == "evenodd"
            else pathops.FillType.WINDING
        )
        part.simplify()
        union = pathops.op(union, part, pathops.PathOp.UNION)
    return union


def build():
    scale = UPM / BOX
    order = [".notdef"] + [f"g_{name}" for name, _, _ in GLYPHS]
    charstrings = {}
    empty = T2CharStringPen(UPM, None)
    charstrings[".notdef"] = empty.getCharString()
    for name, src, _ in GLYPHS:
        pen = T2CharStringPen(UPM, None)
        # SVG is y-down from the top; a glyph is y-up from the baseline.
        outline(SRC / f"{src}.svg").draw(
            TransformPen(pen, (scale, 0, 0, -scale, 0, UPM))
        )
        charstrings[f"g_{name}"] = pen.getCharString()

    fb = FontBuilder(UPM, isTTF=False)
    fb.setupGlyphOrder(order)
    fb.setupCharacterMap({cp: f"g_{name}" for name, _, cp in GLYPHS})
    fb.setupCFF(FAMILY, {"FullName": FAMILY}, charstrings, {})
    fb.setupHorizontalMetrics({g: (UPM, 0) for g in order})
    fb.setupHorizontalHeader(ascent=UPM, descent=0)
    # App Store Connect refuses a binary whose font has no full name (ITMS-90853,
    # 'name' table usability), so the table carries every record a font is
    # looked up by, matching the CFF table's FontName and FullName.
    fb.setupNameTable(
        {
            "familyName": FAMILY,
            "styleName": "Regular",
            "uniqueFontIdentifier": f"{FAMILY};Version 1.000",
            "fullName": FAMILY,
            "version": "Version 1.000",
            "psName": FAMILY,
        }
    )
    fb.setupOS2(
        sTypoAscender=UPM,
        sTypoDescender=0,
        sTypoLineGap=0,
        usWinAscent=UPM,
        usWinDescent=0,
    )
    fb.setupPost()
    fb.save(FONT)

    lines = [
        "// Generated by tool/service_glyphs/build_font.py. Do not edit by hand:",
        "// change the SVG sources or the script and rebuild.",
        "",
        "import 'package:flutter/widgets.dart';",
        "",
        "/// One mark per service, from `assets/fonts/CupolaServices.otf`.",
        "///",
        "/// Reached through `ServiceKey.icon`, never directly.",
        "abstract final class ServiceGlyphs {",
        f"  static const String fontFamily = '{FAMILY}';",
    ]
    for name, _, cp in GLYPHS:
        lines += [
            "",
            f"  static const IconData {name} = IconData(",
            f"    0x{cp:X},",
            "    fontFamily: fontFamily,",
            "  );",
        ]
    lines += ["}", ""]
    DART.write_text("\n".join(lines))
    print(f"{len(GLYPHS)} glyphs -> {FONT.relative_to(ROOT)}, {DART.relative_to(ROOT)}")


if __name__ == "__main__":
    build()
